      var p = n.parentNode;
      if (!p || /^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.nodeName) || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      if (p.closest && p.closest("[data-notr]")) return NodeFilter.FILTER_REJECT;
