import asyncio
from playwright.async_api import async_playwright
B="http://localhost:8765/camello/"
SIM="""const mm=window.matchMedia.bind(window);window.matchMedia=(q)=>q.includes('display-mode: standalone')?{matches:true,media:q,addEventListener(){},removeEventListener(){}}:mm(q);"""
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--no-sandbox"])
    ctx=await b.new_context(viewport={"width":390,"height":844},device_scale_factor=2,geolocation={"latitude":3.41,"longitude":-76.35},permissions=["geolocation"]); await ctx.add_init_script(SIM)
    pg=await ctx.new_page(); errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    await pg.goto(B+"#/registro"); await pg.wait_for_selector("[data-selector-ciudad]")
    await pg.click("[data-selector-ciudad]"); await pg.wait_for_selector(".cajon"); await pg.wait_for_timeout(400)
    print("menú abierto | departamentos:", await pg.locator(".cajon-item").count()-1, "| teclado en buscador:", await pg.evaluate("document.activeElement.type"))
    await pg.screenshot(path="/home/claude/c_menu.png")
    async def buscar(t):
        await pg.fill(".selector-buscar input", t); await pg.wait_for_timeout(100)
        r=[x.split("\n")[0] for x in await pg.locator(".selector-opcion").all_inner_texts()]
        return r[:5] if r else ("VACÍO" if await pg.locator(".selector-vacio").count() else [])
    for t in ["bogo","MEDELLÍN","valle","candela","zzz"]: print(f"  '{t}' ->", await buscar(t))
    await pg.fill(".selector-buscar input","cal"); await pg.wait_for_timeout(100); await pg.screenshot(path="/home/claude/c_buscar.png")
    await pg.fill(".selector-buscar input",""); await pg.wait_for_timeout(100)
    await pg.click(".cajon-item >> text=Valle del Cauca"); await pg.wait_for_timeout(450)
    print("submenú Valle:", await pg.inner_text(".cajon-sub .cajon-titulo"), "|", await pg.locator(".cajon-sub .selector-opcion").count(), "ciudades")
    await pg.screenshot(path="/home/claude/c_sub.png")
    await pg.click(".cajon-sub [data-volver]"); await pg.wait_for_timeout(400)
    print("volver -> sub oculto:", await pg.locator(".cajon-sub").is_hidden())
    await pg.click(".cajon-item >> text=Nariño"); await pg.wait_for_timeout(400)
    await pg.click(".cajon-sub .selector-opcion >> text=Pasto"); await pg.wait_for_timeout(400)
    print("elige Pasto ->", await pg.input_value("#f-ciudad"), "| cerrado:", await pg.locator(".cajon").count()==0)
    await pg.click("[data-selector-ciudad]"); await pg.wait_for_timeout(400)
    print("marca depto actual:", await pg.inner_text(".cajon-item.tiene-actual span"), "| nota:", await pg.inner_text(".cajon-nota"))
    await pg.click(".cajon-item.destacado"); await pg.wait_for_timeout(400)
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(400)
    print("Escape en submenú vuelve al menú:", await pg.locator(".cajon").count()==1 and await pg.locator(".cajon-sub").is_hidden())
    await pg.keyboard.press("Escape"); await pg.wait_for_timeout(400)
    print("Escape cierra sin cambiar:", await pg.locator(".cajon").count()==0, await pg.input_value("#f-ciudad"))
    await pg.click("[data-selector-ciudad]"); await pg.wait_for_timeout(400)
    await pg.mouse.click(380, 400); await pg.wait_for_timeout(400)
    print("tocar fuera cierra:", await pg.locator(".cajon").count()==0)
    await pg.click("[data-selector-ciudad]"); await pg.wait_for_timeout(400)
    await pg.fill(".selector-buscar input","candela"); await pg.press(".selector-buscar input","Enter"); await pg.wait_for_timeout(400)
    print("Enter elige ->", await pg.input_value("#f-ciudad"))
    await pg.click("[data-selector-ciudad]"); await pg.wait_for_timeout(400)
    await pg.click(".selector-gps"); await pg.wait_for_timeout(900)
    print("GPS ->", await pg.input_value("#f-ciudad"))
    print("ERRORES:",errs)
    await b.close()
asyncio.run(main())
